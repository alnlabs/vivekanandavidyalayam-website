export function schoolJsonLd() {
  return {
    '@context': 'https://schema.org',
    '@type': 'School',
    '@id': `${site.url}/#school`,
    name: site.name,
    url: site.url,
    description: site.description,
    image: `${site.url}/og-image.jpg`,
    logo: `${site.url}/logo-seal.png`,
    address: {
      '@type': 'PostalAddress',
      addressLocality: site.village,
      addressRegion: site.state,
      postalCode: site.pincode,
      addressCountry: 'IN',
    },
    geo: {
      '@type': 'GeoCoordinates',
      latitude: site.geo.latitude,
      longitude: site.geo.longitude,
    },
    areaServed: {
      '@type': 'AdministrativeArea',
      name: `${site.district} District, ${site.state}`,
    },
    employee: [
      {
        '@type': 'Person',
        name: site.leadership.principal.name,
        jobTitle: site.leadership.principal.role,
      },
      {
        '@type': 'Person',
        name: site.leadership.vicePrincipal.name,
        jobTitle: site.leadership.vicePrincipal.role,
      },
    ],
    sameAs: [site.alumniUrl],
  };
}
